import { defineRouteMiddleware } from '@astrojs/starlight/route-data';

// Every docs page shows the same notice, so readers who land on any page
// (from the homepage button or from a search engine) see it.
const repo = 'https://github.com/PlateRelay/PlateRelay';
const notice: Record<string, string> = {
  'zh-CN': `文档编写中：当前文档由 LLM 根据仓库现状生成，部分内容可能与最新实现不一致。如有出入，以 <a href="${repo}">PlateRelay/PlateRelay</a> 仓库的 README 与源码为准。`,
  en: `Documentation in progress: these pages are generated by an LLM from the repository and may not reflect the latest implementation. If anything differs, the README and source code in <a href="${repo}">PlateRelay/PlateRelay</a> take precedence.`,
};

export const onRequest = defineRouteMiddleware((context) => {
  const route = context.locals.starlightRoute;
  route.entry.data.banner = { content: notice[route.lang] ?? notice.en };
});
